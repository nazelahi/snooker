--
create table if not exists settings (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default now(),
  key text unique,
  value jsonb
);


--
-- Define a function to get user role
--
create or replace function get_user_role(user_id uuid)
returns text
language plpgsql
security definer
set search_path = public
as $$
begin
  if (select (raw_user_meta_data->>'isAdmin')::boolean from auth.users where id = user_id) then
    return 'admin';
  else
    return 'user';
  end if;
end;
$$;


--
-- Create a function to handle new user creation
--
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.players (id, name, email, initials)
  values (
    new.id,
    new.raw_user_meta_data->>'full_name',
    new.email,
    substring(new.raw_user_meta_data->>'full_name' from 1 for 1) || substring(split_part(new.raw_user_meta_data->>'full_name', ' ', 2) from 1 for 1)
  );
  return new;
end;
$$;

--
-- Create a trigger to call the handle_new_user function on new user creation
--
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();


--
-- Set up Storage!
--
insert into storage.buckets (id, name, public)
values ('avatars', 'avatars', true)
on conflict (id) do nothing;

--
-- Set up RLS policies for storage
--
-- Avatars can be read by anyone
create policy "anyone_can_read_avatars"
on storage.objects for select
to public
using ( bucket_id = 'avatars' );

-- Avatars can only be uploaded by the owner of the avatar
create policy "user_can_upload_avatar"
on storage.objects for insert
to public
with check (
  bucket_id = 'avatars'
  and owner = auth.uid()
);

create policy "user_can_update_avatar"
on storage.objects for update
to public
using (
  bucket_id = 'avatars'
  and owner = auth.uid()
);

--
-- Set up Row Level Security (RLS) policies
--
-- Players
alter table players enable row level security;
drop policy if exists "players_are_public" on players;
create policy "players_are_public" on players for select to public using (true);
drop policy if exists "users_can_update_own_player" on players;
create policy "users_can_update_own_player" on players for update to public using (auth.uid() = id);
drop policy if exists "admins_can_do_anything_on_players" on players;
create policy "admins_can_do_anything_on_players" on players for all to public using (get_user_role(auth.uid()) = 'admin');


-- Matches
alter table matches enable row level security;
drop policy if exists "matches_are_public" on matches;
create policy "matches_are_public" on matches for select to public using (true);
drop policy if exists "users_can_manage_own_matches" on matches;
create policy "users_can_manage_own_matches" on matches for all to public using (
  auth.uid() in (select id from players where name = winner or name = loser)
);
drop policy if exists "admins_can_do_anything_on_matches" on matches;
create policy "admins_can_do_anything_on_matches" on matches for all to public using (get_user_role(auth.uid()) = 'admin');

