--
-- Create a table for public profiles
--
create table if not exists players (
  id uuid not null primary key,
  created_at timestamp with time zone default now(),
  name text,
  email text,
  skill_level text default 'Beginner'::text,
  matches_played integer default 0,
  win_rate text default '0%'::text,
  highest_break integer default 0,
  avatar text,
  initials text,
  wins integer default 0,
  losses integer default 0,
  average_break integer default 0
);

--
-- Create a table for matches
--
create table if not exists matches (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default now(),
  winner text,
  loser text,
  score text,
  date timestamp with time zone,
  media jsonb,
  comments jsonb,
  pending_score jsonb,
  tournament_id bigint
);

--
-- Create a table for tournaments
--
create table if not exists tournaments (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default now(),
  name text,
  format text,
  players integer,
  status text,
  rules text[],
  image text,
  "pendingPlayers" text[],
  "registeredPlayers" text[],
  location text,
  winner text,
  bracket jsonb,
  tournament_id bigint
);

--
-- Create a table for notices
--
create table if not exists notices (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default now(),
  title text,
  content text,
  date timestamp with time zone
);

--
-- Create a table for upcoming matches
--
create table if not exists upcoming_matches (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default now(),
  player1 text,
  player2 text,
  date date,
  time time without time zone,
  tournament_id bigint
);

--
-- Create a table for live matches
--
create table if not exists live_matches (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default now(),
  tournament_id bigint,
  tournament_name text,
  player1 text,
  player2 text,
  score1 integer,
  score2 integer
);

--
-- Create a table for notifications
--
create table if not exists notifications (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default now(),
  user_name text,
  title text,
  description text,
  read boolean default false,
  date timestamp with time zone,
