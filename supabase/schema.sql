CREATE POLICY "Authenticated users can apply to tournaments" ON tournaments FOR UPDATE
  USING (auth.role() = 'authenticated')
  WITH CHECK (
    NOT (pendingPlayers @> (SELECT pendingPlayers FROM tournaments WHERE id = tournaments.id)) OR
    (pendingPlayers IS NULL OR array_length(pendingPlayers, 1) < array_length(tournaments.pendingPlayers, 1))
  );

