--
-- Create a helper function to get user name
--
CREATE OR REPLACE FUNCTION get_user_name()
RETURNS TEXT AS $$
BEGIN
  RETURN (
    SELECT raw_user_meta_data->>'full_name' FROM auth.users WHERE id = auth.uid()
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

--
-- Create a helper function to get user name by email
--
CREATE OR REPLACE FUNCTION get_user_name_by_email(user_email TEXT)
RETURNS TEXT AS $$
BEGIN
  RETURN (SELECT raw_user_meta_data->>'full_name' FROM auth.users WHERE email = user_email);
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

