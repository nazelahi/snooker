-- 3. Row Level Security (RLS) Policies
-- These policies ensure that users can only access and modify data they are authorized to.

-- Function to get the current user's full name from auth metadata
CREATE OR REPLACE FUNCTION public.get_user_full_name()
RETURNS text
LANGUAGE sql
SECURITY DEFINER
AS $$
  SELECT auth.user_metadata->>'full_name' FROM auth.users WHERE id = auth.uid();
$$;

-- Players Table Policies
-- Allow anyone to view player profiles
CREATE POLICY "Enable read access for all users" ON public.players FOR SELECT USING (true);
-- Allow authenticated users to update their own profile
CREATE POLICY "Enable update for users based on name" ON public.players FOR UPDATE USING ((get_user_full_name() = name));
-- Allow admin to do anything
CREATE POLICY "Enable all access for admin" ON public.players FOR ALL USING ((auth.jwt()->>'email' = 'admin@gmail.com'));


-- Matches, Upcoming Matches, Live Matches, Tournaments, Notices, Settings Tables Policies
-- Allow public read access to everyone
CREATE POLICY "Enable read access for all users" ON public.matches FOR SELECT USING (true);
CREATE POLICY "Enable read access for all users" ON public.upcoming_matches FOR SELECT USING (true);
CREATE POLICY "Enable read access for all users" ON public.live_matches FOR SELECT USING (true);
CREATE POLICY "Enable read access for all users" ON public.tournaments FOR SELECT USING (true);
CREATE POLICY "Enable read access for all users" ON public.notices FOR SELECT USING (true);
CREATE POLICY "Enable read access for all users" ON public.settings FOR SELECT USING (true);
-- Allow admin to do anything on these tables
CREATE POLICY "Enable all access for admin" ON public.matches FOR ALL USING ((auth.jwt()->>'email' = 'admin@gmail.com'));
CREATE POLICY "Enable all access for admin" ON public.upcoming_matches FOR ALL USING ((auth.jwt()->>'email' = 'admin@gmail.com'));
CREATE POLICY "Enable all access for admin" ON public.live_matches FOR ALL USING ((auth.jwt()->>'email' = 'admin@gmail.com'));
CREATE POLICY "Enable all access for admin" ON public.tournaments FOR ALL USING ((auth.jwt()->>'email' = 'admin@gmail.com'));
CREATE POLICY "Enable all access for admin" ON public.notices FOR ALL USING ((auth.jwt()->>'email' = 'admin@gmail.com'));
CREATE POLICY "Enable all access for admin" ON public.settings FOR ALL USING ((auth.jwt()->>'email' = 'admin@gmail.com'));
-- Allow authenticated users to create match reports/comments and apply for tournaments
CREATE POLICY "Enable insert for authenticated users" ON public.matches FOR INSERT WITH CHECK (auth.role() = 'authenticated');
CREATE POLICY "Enable update for authenticated users" ON public.matches FOR UPDATE USING (auth.role() = 'authenticated');
CREATE POLICY "Enable update for authenticated users" ON public.tournaments FOR UPDATE USING (auth.role() = 'authenticated');


-- Notifications Table Policies
-- Allow users to view and manage their own notifications
CREATE POLICY "Enable access for users based on name" ON public.notifications FOR ALL USING ((get_user_full_name() = user_name));
-- Allow admin to create notifications for any user
CREATE POLICY "Enable insert for admin" ON public.notifications FOR INSERT WITH CHECK ((auth.jwt()->>'email' = 'admin@gmail.com'));


-- 4. Storage Policies
-- Avatars Bucket Policies
-- Allow anyone to view avatars
CREATE POLICY "Enable read access for all users" ON storage.objects FOR SELECT USING (bucket_id = 'avatars');
-- Allow authenticated users to upload their own avatar
CREATE POLICY "Enable insert for authenticated users" ON storage.objects FOR INSERT WITH CHECK (bucket_id = 'avatars' AND auth.role() = 'authenticated');
-- Allow users to update their own avatar
CREATE POLICY "Enable update for users based on owner" ON storage.objects FOR UPDATE USING (bucket_id = 'avatars' AND auth.uid() = owner);
-- Allow admin to perform any action on avatars
CREATE POLICY "Enable all access for admin" ON storage.objects FOR ALL USING (bucket_id = 'avatars' AND (auth.jwt()->>'email' = 'admin@gmail.com'));
