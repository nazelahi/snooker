--
-- Supabase schema for the CueScore Project
--

-- 1. Create Tables

-- Table to store player information
CREATE TABLE public.players (
    id bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    name text NOT NULL,
    skill_level text NOT NULL DEFAULT 'Beginner'::text,
    matches_played integer NOT NULL DEFAULT 0,
    win_rate text NOT NULL DEFAULT '0%'::text,
    highest_break integer NOT NULL DEFAULT 0,
    avatar text,
    initials text NOT NULL,
    wins integer DEFAULT 0,
    losses integer DEFAULT 0,
    average_break integer DEFAULT 0,
    achievements jsonb
);
ALTER TABLE public.players ENABLE ROW LEVEL SECURITY;

-- Table to store tournament information
CREATE TABLE public.tournaments (
    id bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    name text NOT NULL,
    format text NOT NULL DEFAULT 'Knockout'::text,
    players integer NOT NULL DEFAULT 8,
    status text NOT NULL DEFAULT 'Upcoming'::text,
    rules jsonb,
    image text,
    pendingPlayers jsonb,
    registeredPlayers jsonb,
    location text,
    winner text,
    bracket jsonb
);
ALTER TABLE public.tournaments ENABLE ROW LEVEL SECURITY;

-- Table to store completed match results
CREATE TABLE public.matches (
    id bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    winner text NOT NULL,
    loser text NOT NULL,
    score text NOT NULL,
    date timestamp with time zone NOT NULL,
    media jsonb,
    comments jsonb,
    pending_score jsonb,
    tournament_id bigint,
    CONSTRAINT matches_tournament_id_fkey FOREIGN KEY (tournament_id) REFERENCES public.tournaments (id) ON DELETE SET NULL
);
ALTER TABLE public.matches ENABLE ROW LEVEL SECURITY;


-- Table to store upcoming, scheduled matches
CREATE TABLE public.upcoming_matches (
    id bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    player1 text NOT NULL,
    player2 text NOT NULL,
    date date NOT NULL,
    time time without time zone NOT NULL,
    tournament_id bigint,
    CONSTRAINT upcoming_matches_tournament_id_fkey FOREIGN KEY (tournament_id) REFERENCES public.tournaments (id) ON DELETE CASCADE
);
ALTER TABLE public.upcoming_matches ENABLE ROW LEVEL SECURITY;


-- Table to store live, in-progress matches
CREATE TABLE public.live_matches (
    id bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    tournament_id bigint NOT NULL,
    tournament_name text,
    player1 text NOT NULL,
    player2 text NOT NULL,
    score1 integer NOT NULL DEFAULT 0,
    score2 integer NOT NULL DEFAULT 0,
    CONSTRAINT live_matches_tournament_id_fkey FOREIGN KEY (tournament_id) REFERENCES public.tournaments (id) ON DELETE CASCADE
);
ALTER TABLE public.live_matches ENABLE ROW LEVEL SECURITY;


-- Table for user notifications
CREATE TABLE public.notifications (
    id bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    user_name text NOT NULL,
    title text NOT NULL,
    description text NOT NULL,
    read boolean NOT NULL DEFAULT false,
    date timestamp with time zone NOT NULL,
    link text
);
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;

-- Table for club notices/announcements
CREATE TABLE public.notices (
    id bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    title text NOT NULL,
    content text NOT NULL,
    date timestamp with time zone NOT NULL
);
ALTER TABLE public.notices ENABLE ROW LEVEL SECURITY;


-- Table for general site settings (e.g., name, logo)
CREATE TABLE public.settings (
    id bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    key text NOT NULL UNIQUE,
    value jsonb
);
ALTER TABLE public.settings ENABLE ROW LEVEL SECURITY;


