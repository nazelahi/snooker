
--
-- Create a table for public profiles
--
CREATE TABLE public.players (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  name TEXT NOT NULL,
  skill_level TEXT NOT NULL DEFAULT 'Beginner',
  matches_played BIGINT NOT NULL DEFAULT 0,
  win_rate TEXT NOT NULL DEFAULT '0%',
  highest_break BIGINT NOT NULL DEFAULT 0,
  avatar TEXT,
  initials TEXT,
  wins BIGINT DEFAULT 0,
  losses BIGINT DEFAULT 0,
  average_break BIGINT DEFAULT 0,
  achievements JSONB,
  CONSTRAINT "players_name_key" UNIQUE (name)
);

--
-- Create tournaments table
--
CREATE TABLE public.tournaments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    format TEXT NOT NULL,
    players INT NOT NULL,
    status TEXT NOT NULL,
    rules JSONB,
    image TEXT,
    pendingPlayers TEXT[],
    registeredPlayers TEXT[],
    location TEXT,
    winner TEXT,
    bracket JSONB,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

--
-- Create matches table
--
CREATE TABLE public.matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    winner TEXT NOT NULL,
    loser TEXT NOT NULL,
    score TEXT NOT NULL,
    date TIMESTAMPTZ NOT NULL,
    media JSONB,
    comments JSONB,
    pending_score JSONB,
    tournament_id BIGINT REFERENCES public.tournaments (id) ON DELETE SET NULL
);

--
-- Create upcoming_matches table
--
CREATE TABLE public.upcoming_matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player1 TEXT NOT NULL,
    player2 TEXT NOT NULL,
    date DATE NOT NULL,
    time TIME NOT NULL,
    tournament_id BIGINT REFERENCES public.tournaments (id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

--
-- Create live_matches table
--
CREATE TABLE public.live_matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tournament_id BIGINT REFERENCES public.tournaments(id) ON DELETE CASCADE,
    tournament_name TEXT,
    player1 TEXT NOT NULL,
    player2 TEXT NOT NULL,
    score1 INT NOT NULL,
    score2 INT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

--
-- Create notices table
--
CREATE TABLE public.notices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    content TEXT NOT NULL,
    date TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);


--
-- Create notifications table
--
CREATE TABLE public.notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_name TEXT NOT NULL,
    title TEXT NOT NULL,
    description TEXT NOT NULL,
    read BOOLEAN DEFAULT FALSE,
    date TIMESTAMPTZ NOT NULL,
    link TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);


--
-- Create settings table
--
CREATE TABLE public.settings (
    key TEXT PRIMARY KEY,
    value JSONB
);

