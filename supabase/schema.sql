--
-- Helper Functions for RLS
--
CREATE OR REPLACE FUNCTION get_user_name()
RETURNS TEXT AS $$
  SELECT auth.jwt()->>'full_name';
$$ LANGUAGE sql STABLE;

CREATE OR REPLACE FUNCTION get_user_email()
RETURNS TEXT AS $$
  SELECT auth.email();
$$ LANGUAGE sql STABLE;

