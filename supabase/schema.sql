-- Allow public read access to all tables
CREATE POLICY "Allow public read access" ON public.players FOR SELECT USING (TRUE);
CREATE POLICY "Allow public read access" ON public.matches FOR SELECT USING (TRUE);
CREATE POLICY "Allow public read access" ON public.tournaments FOR SELECT USING (TRUE);
CREATE POLICY "Allow public read access" ON public.upcoming_matches FOR SELECT USING (TRUE);
CREATE POLICY "Allow public read access" ON public.live_matches FOR SELECT USING (TRUE);
CREATE POLICY "Allow public read access" ON public.notices FOR SELECT USING (TRUE);
CREATE POLICY "Allow public read access" ON public.settings FOR SELECT USING (TRUE);


-- Allow authenticated users to manage their own data
CREATE POLICY "Allow users to manage their own notifications" ON public.notifications
  FOR ALL
  USING (get_user_name() = user_name)
  WITH CHECK (get_user_name() = user_name);

CREATE POLICY "Allow users to update their own player profile" ON public.players
  FOR UPDATE
  USING (get_user_name() = name)
  WITH CHECK (get_user_name() = name);
  
CREATE POLICY "Allow users to insert their own player profile during signup" ON public.players
  FOR INSERT
  WITH CHECK (get_user_name() = name);

CREATE POLICY "Allow users to manage their tournament applications" ON public.tournaments
  FOR UPDATE
  USING (
    array_position(pendingPlayers, get_user_name()) IS NOT NULL OR
    array_position(registeredPlayers, get_user_name()) IS NOT NULL
  )
  WITH CHECK (
    array_position(pendingPlayers, get_user_name()) IS NOT NULL OR
    array_position(registeredPlayers, get_user_name()) IS NOT NULL
  );

CREATE POLICY "Allow users to update matches they are part of" ON public.matches
  FOR UPDATE
  USING (get_user_name() = winner OR get_user_name() = loser)
  WITH CHECK (get_user_name() = winner OR get_user_name() = loser);


