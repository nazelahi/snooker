-- USERS Table
-- Stores public user data, linked to auth.users
create table if not exists public.users (
    id uuid not null primary key,
    name text,
    email text,
    avatar text,
    role text default 'user'
);
alter table public.users enable row level security;
create policy "Public users are viewable by everyone." on public.users for select using (true);
create policy "Users can insert their own profile." on public.users for insert with check (auth.uid() = id);
create policy "Users can update their own profile." on public.users for update using (auth.uid() = id) with check (auth.uid() = id);
alter table public.users add constraint unique_email unique (email);


-- PLAYERS Table
-- Stores player-specific stats and links to a user profile
create table if not exists public.players (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    name text not null,
    skill_level text not null default 'Beginner',
    matches_played integer not null default 0,
    win_rate text not null default '0%',
    highest_break integer not null default 0,
    avatar text,
    initials text,
    wins integer default 0,
    losses integer default 0,
    average_break integer default 0,
    user_id uuid references public.users(id) on delete set null
);
alter table public.players enable row level security;
create policy "Players are viewable by everyone." on public.players for select using (true);
create policy "Authenticated users can create players." on public.players for insert with check (auth.role() = 'authenticated');
create policy "Users can update their own player profile." on public.players for update using (auth.uid() = user_id);
create policy "Admins can update any player." on public.players for update using (exists (select 1 from users where id = auth.uid() and role = 'admin'));
create policy "Admins can delete players." on public.players for delete using (exists (select 1 from users where id = auth.uid() and role = 'admin'));


