
--
-- Create the users table
--
CREATE TABLE users (
    id uuid REFERENCES auth.users(id) PRIMARY KEY,
    name text,
    email text UNIQUE,
    role text DEFAULT 'user',
    avatar text
);

--
-- Create the players table
--
CREATE TABLE players (
    id bigint generated by default as identity,
    created_at timestamp with time zone not null default now(),
    name text not null,
    skill_level text not null,
    matches_played bigint not null,
    win_rate text not null,
    highest_break bigint not null,
    avatar text,
    initials text,
    wins bigint,
    losses bigint,
    average_break real,
    user_id uuid,
    CONSTRAINT players_pkey PRIMARY KEY (id),
    CONSTRAINT players_name_key UNIQUE (name),
    CONSTRAINT players_user_id_fkey FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL
);

--
-- Create the tournaments table
--
CREATE TABLE tournaments (
    id bigint generated by default as identity,
    name text,
    format text,
    players bigint,
    status text,
    rules text[],
    image text,
    pendingPlayers text[],
    registeredPlayers text[],
    location text,
    winner text,
    bracket jsonb,
    CONSTRAINT tournaments_pkey PRIMARY KEY (id)
);

--
-- Create the matches table
--
CREATE TABLE matches (
    id bigint generated by default as identity,
    winner text,
    loser text,
    score text,
    date text,
    media text[],
    comments jsonb,
    pending_score jsonb,
    tournament_id bigint,
    CONSTRAINT matches_pkey PRIMARY KEY (id),
    CONSTRAINT matches_tournament_id_fkey FOREIGN KEY (tournament_id) REFERENCES tournaments (id)
);

--
-- Create the upcoming_matches table
--
CREATE TABLE upcoming_matches (
    id bigint generated by default as identity,
    player1 text,
    player2 text,
    date text,
    "time" text,
    tournament_id bigint,
    CONSTRAINT upcoming_matches_pkey PRIMARY KEY (id),
    CONSTRAINT upcoming_matches_tournament_id_fkey FOREIGN KEY (tournament_id) REFERENCES tournaments (id)
);

--
-- Create the live_matches table
--
CREATE TABLE live_matches (
    id bigint generated by default as identity,
    tournament_id bigint,
    tournament_name text,
    player1 text,
    player2 text,
    score1 bigint,
    score2 bigint,
    CONSTRAINT live_matches_pkey PRIMARY KEY (id),
    CONSTRAINT live_matches_tournament_id_fkey FOREIGN KEY (tournament_id) REFERENCES tournaments (id)
);

--
-- Create the notices table
--
CREATE TABLE notices (
    id bigint generated by default as identity,
    title text,
    content text,
    date text,
    created_at timestamp with time zone not null default now(),
    CONSTRAINT notices_pkey PRIMARY KEY (id)
);

--
-- Create the notifications table
--
CREATE TABLE notifications (
    id bigint generated by default as identity,
    created_at timestamp with time zone not null default now(),
    user_id uuid not null,
    title text,
    description text,
    read boolean not null default false,
    date text,
    link text,
    CONSTRAINT notifications_pkey PRIMARY KEY (id),
    CONSTRAINT notifications_user_id_fkey FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);


--
-- Create the settings table
--
CREATE TABLE settings (
    key text primary key,
    value jsonb
);

--
-- Create function to handle new user creation
--
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  -- Create a record in the public.users table
  INSERT INTO public.users (id, name, email, avatar, role)
  VALUES (
    NEW.id, 
    NEW.raw_user_meta_data->>'full_name',
    NEW.email,
    NEW.raw_user_meta_data->>'avatar_url',
    CASE 
      WHEN NEW.email = 'imnazelahi@gmail.com' THEN 'admin'
      ELSE 'user'
    END
  );

  -- Create a corresponding record in the public.players table
  INSERT INTO public.players (user_id, name, initials, avatar, skill_level, matches_played, wins, losses, win_rate, highest_break, average_break)
  VALUES (
    NEW.id,
    NEW.raw_user_meta_data->>'full_name',
    SUBSTRING(NEW.raw_user_meta_data->>'full_name' from 1 for 1) || SUBSTRING(SPLIT_PART(NEW.raw_user_meta_data->>'full_name', ' ', 2) from 1 for 1),
    NEW.raw_user_meta_data->>'avatar_url',
    'Beginner', 0, 0, 0, '0%', 0, 0
  );
  
  RETURN NEW;
END;
$$;


--
-- Create trigger to call handle_new_user on new auth.users record
--
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();


