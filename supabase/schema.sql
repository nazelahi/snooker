
--
-- Create a table for public players
--
CREATE TABLE
  players (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    name TEXT NOT NULL,
    skill_level TEXT NOT NULL DEFAULT 'Beginner',
    matches_played BIGINT NOT NULL DEFAULT 0,
    win_rate TEXT NOT NULL DEFAULT '0%',
    highest_break BIGINT NOT NULL DEFAULT 0,
    avatar TEXT,
    initials TEXT,
    wins BIGINT DEFAULT 0,
    losses BIGINT DEFAULT 0,
    average_break BIGINT DEFAULT 0,
    achievements JSONB,
    CONSTRAINT players_name_key UNIQUE (name)
  );

--
-- Create a table for matches
--
CREATE TABLE
  matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    winner TEXT NOT NULL,
    loser TEXT NOT NULL,
    score TEXT NOT NULL,
    date TIMESTAMP WITH TIME ZONE NOT NULL,
    media JSONB,
    comments JSONB,
    pending_score JSONB,
    tournament_id BIGINT,
    CONSTRAINT matches_winner_fkey FOREIGN KEY (winner) REFERENCES players (name),
    CONSTRAINT matches_loser_fkey FOREIGN KEY (loser) REFERENCES players (name),
    CONSTRAINT matches_tournament_id_fkey FOREIGN KEY (tournament_id) REFERENCES tournaments (id) ON DELETE SET NULL
  );

--
-- Create a table for upcoming matches
--
CREATE TABLE
  upcoming_matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    player1 TEXT NOT NULL,
    player2 TEXT NOT NULL,
    date DATE NOT NULL,
    time TIME WITH TIME ZONE NOT NULL,
    tournament_id BIGINT,
    CONSTRAINT upcoming_matches_player1_fkey FOREIGN KEY (player1) REFERENCES players (name) ON DELETE CASCADE,
    CONSTRAINT upcoming_matches_player2_fkey FOREIGN KEY (player2) REFERENCES players (name) ON DELETE CASCADE,
    CONSTRAINT upcoming_matches_tournament_id_fkey FOREIGN KEY (tournament_id) REFERENCES tournaments (id) ON DELETE SET NULL
  );

--
-- Create a table for live matches
--
CREATE TABLE
  live_matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    player1 TEXT NOT NULL,
    player2 TEXT NOT NULL,
    score1 INTEGER NOT NULL DEFAULT 0,
    score2 INTEGER NOT NULL DEFAULT 0,
    tournament_id BIGINT,
    tournament_name TEXT,
    CONSTRAINT live_matches_player1_fkey FOREIGN KEY (player1) REFERENCES players (name) ON DELETE CASCADE,
    CONSTRAINT live_matches_player2_fkey FOREIGN KEY (player2) REFERENCES players (name) ON DELETE CASCADE,
    CONSTRAINT live_matches_tournament_id_fkey FOREIGN KEY (tournament_id) REFERENCES tournaments (id) ON DELETE SET NULL
  );

