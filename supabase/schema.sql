--
-- RLS Policies for players table
--
ALTER TABLE players ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Public players are viewable by everyone." ON players;
CREATE POLICY "Public players are viewable by everyone." ON players FOR SELECT USING (TRUE);
DROP POLICY IF EXISTS "Users can insert their own player profile." ON players;
CREATE POLICY "Users can insert their own player profile." ON players FOR INSERT WITH CHECK (auth.uid() IS NOT NULL AND name = get_user_name());
DROP POLICY IF EXISTS "Users can update their own player profile." ON players;
CREATE POLICY "Users can update their own player profile." ON players FOR UPDATE USING (auth.uid() IS NOT NULL AND name = get_user_name());

--
-- RLS Policies for matches table
--
ALTER TABLE matches ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Matches are viewable by everyone." ON matches;
CREATE POLICY "Matches are viewable by everyone." ON matches FOR SELECT USING (TRUE);
DROP POLICY IF EXISTS "Authenticated users can create matches." ON matches;
CREATE POLICY "Authenticated users can create matches." ON matches FOR INSERT WITH CHECK (auth.role() = 'authenticated');
DROP POLICY IF EXISTS "Users can update their own matches." ON matches;
CREATE POLICY "Users can update their own matches." ON matches FOR UPDATE USING (
  auth.role() = 'authenticated' AND (
    winner = get_user_name() OR loser = get_user_name()
  )
);

