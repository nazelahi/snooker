
-- Create a table for public players
create table players (
  id bigint generated by default as identity primary key,
  name text not null,
  skill_level text check (skill_level in ('Beginner', 'Intermediate', 'Pro')) not null,
  matches_played integer not null default 0,
  win_rate text not null default '0%',
  highest_break integer not null default 0,
  avatar text,
  initials text not null,
  wins integer default 0,
  losses integer default 0,
  average_break integer default 0,
  created_at timestamptz default now(),
  user_id uuid references auth.users(id)
);

-- Create a table for public tournaments
create table tournaments (
  id bigint generated by default as identity primary key,
  name text not null,
  format text check (format in ('Knockout', 'League', 'Round Robin')) not null,
  players integer not null,
  status text check (status in ('Upcoming', 'In Progress', 'Finished')) not null,
  rules text[],
  image text,
  pendingPlayers text[],
  registeredPlayers text[],
  location text,
  winner text,
  bracket jsonb,
  created_at timestamptz default now()
);

-- Create a table for public matches
create table matches (
    id bigint generated by default as identity primary key,
    winner text not null,
    loser text not null,
    score text not null,
    date timestamptz not null,
    media text[],
    comments jsonb,
    pending_score jsonb,
    tournament_id bigint references tournaments(id),
    created_at timestamptz default now()
);

-- Create a table for upcoming matches
create table upcoming_matches (
    id bigint generated by default as identity primary key,
    player1 text not null,
    player2 text not null,
    date date not null,
    time time not null,
    tournament_id bigint references tournaments(id),
    created_at timestamptz default now()
);

-- Create a table for live matches
create table live_matches (
    id bigint generated by default as identity primary key,
    tournament_id bigint references tournaments(id),
    tournament_name text not null,
    player1 text not null,
    player2 text not null,
    score1 integer not null,
    score2 integer not null,
    created_at timestamptz default now()
);

-- Create a table for site settings
create table settings (
    key text primary key,
    value jsonb not null
);

-- Create a table for notices
create table notices (
    id bigint generated by default as identity primary key,
    title text not null,
    content text not null,
    date timestamptz not null default now(),
    created_at timestamptz default now()
);

-- Create a table for user profiles
create table users (
  id uuid references auth.users(id) not null primary key,
  name text,
  email text,
  role text,
  avatar text,
  created_at timestamptz default now()
);

-- Create a table for notifications
create table notifications (
    id bigint generated by default as identity primary key,
    user_id uuid references public.users(id) not null,
    title text not null,
    description text not null,
    read boolean not null default false,
    date timestamptz not null default now(),
    link text,
    created_at timestamptz default now()
);

-- Helper functions
create or replace function get_user_id()
returns uuid
language sql stable
as $$
  select auth.uid();
$$;

create or replace function get_user_name()
returns text
language sql stable
as $$
  select name from public.users where id = auth.uid();
$$;

create or replace function get_user_email()
returns text
language sql stable
as $$
    select email from public.users where id = auth.uid();
$$;

create or replace function is_admin()
returns boolean
language sql stable
as $$
  select role = 'admin' from public.users where id = auth.uid();
$$;

-- RLS Policies
alter table players enable row level security;
create policy "Players are viewable by everyone." on players for select using (true);
create policy "Users can insert their own player." on players for insert with check (auth.uid() = user_id);
create policy "Users can update their own player." on players for update using (auth.uid() = user_id or is_admin());

alter table tournaments enable row level security;
create policy "Tournaments are viewable by everyone." on tournaments for select using (true);
create policy "Admins can create tournaments." on tournaments for insert with check (is_admin());
create policy "Admins can update tournaments." on tournaments for update using (is_admin());
create policy "Users can apply to tournaments." on tournaments for update with check (
    (pendingPlayers IS NOT NULL AND array_position(pendingPlayers, get_user_name()) IS NULL)
);

alter table matches enable row level security;
create policy "Matches are viewable by everyone." on matches for select using (true);
create policy "Authenticated users can create matches." on matches for insert with check (auth.role() = 'authenticated');
create policy "Users can update their own matches." on matches for update using (
    auth.role() = 'authenticated' and 
    (
        winner = get_user_name() or
        loser = get_user_name() or
        is_admin()
    )
);
create policy "Admins can delete matches." on matches for delete using (is_admin());

alter table upcoming_matches enable row level security;
create policy "Upcoming matches are viewable by everyone." on upcoming_matches for select using (true);
create policy "Admins can manage upcoming matches." on upcoming_matches for all using (is_admin());

alter table live_matches enable row level security;
create policy "Live matches are viewable by everyone." on live_matches for select using (true);
create policy "Admins can manage live matches." on live_matches for all using (is_admin());

alter table settings enable row level security;
create policy "Settings are viewable by everyone." on settings for select using (true);
create policy "Admins can manage settings." on settings for all using (is_admin());

alter table notices enable row level security;
create policy "Notices are viewable by everyone." on notices for select using (true);
create policy "Admins can manage notices." on notices for all using (is_admin());

alter table users enable row level security;
create policy "Users are viewable by everyone." on users for select using (true);
create policy "Users can insert their own profile." on users for insert with check (auth.uid() = id);
create policy "Users can update their own profile." on users for update using (auth.uid() = id);

alter table notifications enable row level security;
create policy "Users can view their own notifications." on notifications for select using (auth.uid() = user_id);
create policy "Users can manage their own notifications." on notifications for all using (auth.uid() = user_id);


