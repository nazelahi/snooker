-- Create tables
create table if not exists public.users (
    id uuid not null primary key references auth.users(id) on delete cascade,
    name text,
    email text,
    role text default 'user',
    avatar text,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create table if not exists public.players (
  id bigint generated by default as identity primary key,
  name text not null,
  skill_level text not null default 'Beginner',
  matches_played integer not null default 0,
  win_rate text not null default '0%',
  highest_break integer not null default 0,
  avatar text,
  initials text,
  wins integer default 0,
  losses integer default 0,
  average_break integer default 0,
  achievements jsonb,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  user_id uuid references public.users(id) on delete set null
);

create table if not exists public.tournaments (
  id bigint generated by default as identity primary key,
  name text not null,
  format text not null,
  players integer not null,
  status text not null,
  rules text[],
  image text,
  pendingPlayers text[],
  registeredPlayers text[],
  location text,
  winner text,
  bracket jsonb,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create table if not exists public.matches (
  id bigint generated by default as identity primary key,
  winner text not null,
  loser text not null,
  score text not null,
  date timestamp with time zone not null,
  media text[],
  comments jsonb,
  pending_score jsonb,
  tournament_id bigint references public.tournaments(id) on delete set null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create table if not exists public.upcoming_matches (
  id bigint generated by default as identity primary key,
  player1 text not null,
  player2 text not null,
  date date not null,
  time time not null,
  tournament_id bigint references public.tournaments(id) on delete set null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create table if not exists public.live_matches (
  id bigint generated by default as identity primary key,
  tournament_id bigint not null references public.tournaments(id) on delete cascade,
  tournament_name text not null,
  player1 text not null,
  player2 text not null,
  score1 integer not null,
  score2 integer not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create table if not exists public.notices (
    id bigint generated by default as identity primary key,
    title text not null,
    content text not null,
    date timestamp with time zone not null,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create table if not exists public.notifications (
    id bigint generated by default as identity primary key,
    user_id uuid not null references public.users(id) on delete cascade,
    title text not null,
    description text not null,
    read boolean not null default false,
    date timestamp with time zone not null,
    link text,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create table if not exists public.settings (
    key text primary key,
    value jsonb not null
);


-- Function to get the role of the current user
create or replace function get_user_role(user_id uuid)
returns text
language plpgsql
as $$
declare
  user_role text;
begin
  select role into user_role from public.users where id = user_id;
  return user_role;
end;
$$;

-- Function to get the email of the current user
create or replace function get_user_email()
returns text
language plpgsql
security definer
as $$
begin
  return auth.jwt()->>'email';
end;
$$;


-- Function to get the name of the current user
create or replace function get_user_name(user_id uuid)
returns text
language plpgsql
as $$
declare
  user_name text;
begin
  select name into user_name from public.users where id = user_id;
  return user_name;
end;
$$;

-- RLS Policies
-- USERS
drop policy if exists "Allow read access to all users" on public.users;
create policy "Allow read access to all users" on public.users for select using (true);
drop policy if exists "Allow individual update access" on public.users;
create policy "Allow individual update access" on public.users for update using (auth.uid() = id);

-- PLAYERS
drop policy if exists "Allow read access to all users" on public.players;
create policy "Allow read access to all users" on public.players for select using (true);
drop policy if exists "Allow insert access for admins" on public.players;
create policy "Allow insert access for admins" on public.players for insert with check (get_user_role(auth.uid()) = 'admin');
drop policy if exists "Allow update access for admins" on public.players;
create policy "Allow update access for admins" on public.players for update using (get_user_role(auth.uid()) = 'admin');
drop policy if exists "Allow delete access for admins" on public.players;
create policy "Allow delete access for admins" on public.players for delete using (get_user_role(auth.uid()) = 'admin');

-- TOURNAMENTS
drop policy if exists "Allow read access to all users" on public.tournaments;
create policy "Allow read access to all users" on public.tournaments for select using (true);
drop policy if exists "Allow all access for admins" on public.tournaments;
create policy "Allow all access for admins" on public.tournaments for all using (get_user_role(auth.uid()) = 'admin');
drop policy if exists "Allow players to apply to tournaments" on public.tournaments;
create policy "Allow players to apply to tournaments" on public.tournaments for update using (
    (pendingPlayers is null or not (pendingPlayers @> array[get_user_name(auth.uid())])) and
    (registeredPlayers is null or not (registeredPlayers @> array[get_user_name(auth.uid())]))
) with check (
    array_position(pendingPlayers, get_user_name(auth.uid())) is not null
);


