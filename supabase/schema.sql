-- Function and Trigger to create user profile on signup
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  -- Create a public user profile
  insert into public.users (id, name, email, avatar, role)
  values (
    new.id,
    new.raw_user_meta_data->>'full_name',
    new.email,
    new.raw_user_meta_data->>'avatar_url',
    case when new.email = 'imnazelahi@gmail.com' then 'admin' else 'user' end
  );
  
  -- Create a corresponding player profile
  insert into public.players (user_id, name, initials, avatar, skill_level, highest_break)
  values (
    new.id,
    new.raw_user_meta_data->>'full_name',
    (regexp_split_to_array(new.raw_user_meta_data->>'full_name', E'\\s+'))[1][1] || (regexp_split_to_array(new.raw_user_meta_data->>'full_name', E'\\s+'))[2][1],
    new.raw_user_meta_data->>'avatar_url',
    'Beginner',
    0
  );
  return new;
end;
$$;

-- drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- Policies for storage bucket
create policy "Media is publicly accessible." on storage.objects
  for select using ( bucket_id = 'media' );

create policy "Authenticated users can upload media." on storage.objects
  for insert with check ( bucket_id = 'media' and auth.role() = 'authenticated' );

create policy "Users can update their own media." on storage.objects
  for update using ( bucket_id = 'media' and auth.uid() = owner );

create policy "Users can delete their own media." on storage.objects
  for delete using ( bucket_id = 'media' and auth.uid() = owner );
