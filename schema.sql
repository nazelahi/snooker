-- Storage policies
CREATE POLICY "Allow public read access to avatars" ON storage.objects FOR SELECT USING ( bucket_id = 'avatars' );
CREATE POLICY "Allow user to manage their own avatar" ON storage.objects FOR INSERT WITH CHECK ( bucket_id = 'avatars' AND auth.uid() = (storage.foldername(name))[1]::uuid );
CREATE POLICY "Allow user to update their own avatar" ON storage.objects FOR UPDATE USING ( bucket_id = 'avatars' AND auth.uid() = (storage.foldername(name))[1]::uuid );
CREATE POLICY "Allow admin full access to avatars" ON storage.objects FOR ALL USING ( bucket_id = 'avatars' AND is_admin() );
