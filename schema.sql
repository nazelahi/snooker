-- RLS Policies for players table
ALTER TABLE public.players ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow public read access" ON public.players FOR SELECT USING (true);
CREATE POLICY "Allow individual user to update their own profile" ON public.players FOR UPDATE USING (auth.uid() = id);
CREATE POLICY "Allow individual user to insert their own profile" ON public.players FOR INSERT WITH CHECK (auth.uid() = id);
CREATE POLICY "Allow admin full access" ON public.players FOR ALL USING (public.is_admin());

-- RLS Policies for avatars bucket
CREATE POLICY "Allow public read access to avatars" ON storage.objects FOR SELECT TO authenticated, anon USING (bucket_id = 'player_avatars');
CREATE POLICY "Allow user to manage their own avatar" ON storage.objects FOR INSERT WITH CHECK (auth.uid() = owner_id AND bucket_id = 'player_avatars');
CREATE POLICY "Allow user to update their own avatar" ON storage.objects FOR UPDATE USING (auth.uid() = owner_id AND bucket_id = 'player_avatars');
CREATE POLICY "Allow user to delete their own avatar" ON storage.objects FOR DELETE USING (auth.uid() = owner_id AND bucket_id = 'player_avatars');
CREATE POLICY "Allow admin full access to avatars" ON storage.objects FOR ALL USING (public.is_admin() AND bucket_id = 'player_avatars');

-- RLS Policies for other tables
ALTER TABLE public.tournaments ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow public read access" ON public.tournaments FOR SELECT USING (true);
CREATE POLICY "Allow admin full access on tournaments" ON public.tournaments FOR ALL USING (public.is_admin());
CREATE POLICY "Allow users to apply to tournaments" ON public.tournaments FOR UPDATE
    USING (auth.uid() IS NOT NULL)
    WITH CHECK (
        (pendingplayers IS NOT NULL AND array_position(pendingplayers, (select raw_user_meta_data->>'full_name' from auth.users where id = auth.uid())) IS NOT NULL) OR
        (registeredplayers IS NOT NULL AND array_position(registeredplayers, (select raw_user_meta_data->>'full_name' from auth.users where id = auth.uid())) IS NOT NULL)
    );

ALTER TABLE public.matches ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Allow public read access" ON public.matches FOR SELECT USING (true);
CREATE POLICY "Allow admin full access on matches" ON public.matches FOR ALL USING (public.is_admin());
CREATE POLICY "Allow users to update their own matches" ON public.matches FOR UPDATE
    USING (
        auth.uid() = (select id from public.players where name = winner) OR
        auth.uid() = (select id from public.players where name = loser)
    );
CREATE POLICY "Allow users to create matches" ON public.matches FOR INSERT WITH CHECK (auth.uid() IS NOT NULL);

