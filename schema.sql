-- Helper function to check for admin role
create or replace function is_admin()
returns boolean
language sql
security definer
set search_path = public
as $$
  select auth.jwt()->>'email' = 'admin@gmail.com';
$$;


-- RLS POLICIES

-- Policies for players
ALTER TABLE public.players ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can see all players" ON public.players FOR SELECT USING (true);
CREATE POLICY "Users can insert their own player" ON public.players FOR INSERT WITH CHECK (auth.uid() = id);
CREATE POLICY "Users can update their own player" ON public.players FOR UPDATE USING (auth.uid() = id);
CREATE POLICY "Admins can select and delete players" ON public.players FOR SELECT, DELETE USING (is_admin());
CREATE POLICY "Admins can insert and update players" ON public.players FOR INSERT, UPDATE USING (is_admin()) WITH CHECK (is_admin());


-- Policies for matches
ALTER TABLE public.matches ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can see all matches" ON public.matches FOR SELECT USING (true);
CREATE POLICY "Authenticated users can insert matches" ON public.matches FOR INSERT WITH CHECK (auth.role() = 'authenticated');
CREATE POLICY "Users can update their own matches or admins" ON public.matches FOR UPDATE USING (is_admin() or (auth.uid() IN (SELECT id from players where name = winner or name = loser)));
CREATE POLICY "Admins can delete matches" ON public.matches FOR DELETE USING (is_admin());

-- Policies for tournaments
ALTER TABLE public.tournaments ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can see all tournaments" ON public.tournaments FOR SELECT USING (true);
CREATE POLICY "Admins can manage tournaments" ON public.tournaments FOR ALL USING (is_admin());
CREATE POLICY "Authenticated users can update tournament player lists" ON public.tournaments FOR UPDATE
    USING (auth.role() = 'authenticated')
    WITH CHECK (
        (
            (SELECT count(*) FROM tournaments t WHERE t.id = tournaments.id and auth.jwt()->>'email' = ANY(t."pendingPlayers")) > 0
        ) OR (
            (SELECT count(*) FROM tournaments t WHERE t.id = tournaments.id and auth.jwt()->>'email' = ANY(t."registeredPlayers")) > 0
        )
    );

-- Policies for notices
ALTER TABLE public.notices ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can see all notices" ON public.notices FOR SELECT USING (true);
CREATE POLICY "Admins can manage notices" ON public.notices FOR ALL USING (is_admin());

-- Policies for notifications
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can only see their own notifications" ON public.notifications FOR SELECT USING (auth.jwt()->>'email' = user_name);
CREATE POLICY "Users can manage their own notifications" ON public.notifications FOR ALL
    USING (auth.jwt()->>'email' = user_name)
    WITH CHECK (auth.jwt()->>'email' = user_name);
CREATE POLICY "Admins can see all notifications" ON public.notifications FOR SELECT USING (is_admin());


-- Policies for settings
ALTER TABLE public.settings ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can see all settings" ON public.settings FOR SELECT USING (true);
CREATE POLICY "Admins can manage settings" ON public.settings FOR ALL USING (is_admin());

-- Policies for upcoming_matches
ALTER TABLE public.upcoming_matches ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can see all upcoming matches" ON public.upcoming_matches FOR SELECT USING (true);
CREATE POLICY "Admins can manage upcoming matches" ON public.upcoming_matches FOR ALL USING (is_admin());


-- Storage policies
CREATE POLICY "Avatar images are publicly accessible." ON storage.objects FOR SELECT USING (bucket_id = 'avatars');
CREATE POLICY "Anyone can upload an avatar." ON storage.objects FOR INSERT WITH CHECK (bucket_id = 'avatars');
CREATE POLICY "Anyone can update their own avatar." ON storage.objects FOR UPDATE
  USING (auth.uid() = owner)
  WITH CHECK (bucket_id = 'avatars');
CREATE POLICY "Admins can manage avatars" ON storage.objects FOR ALL USING (is_admin());

-- Function to call edge function and trigger
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  -- Logic to invoke the Edge Function
  perform net.http_post(
    url:='https://<YOUR_PROJECT_REF>.supabase.co/functions/v1/create-player-profile',
    headers:='{"Content-Type":"application/json", "Authorization": "Bearer " || Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")}',
    body:=json_build_object('record', new)
  );
  return new;
end;
$$;

-- Trigger to call the function on new user creation
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();
