-- Function to call Edge Function
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  perform extensions.http_request(
    -- Supabase API URL with the Edge Function name
    'https://wewkgrrhkhklftmbexav.supabase.co/functions/v1/create-player-profile',
    'POST',
    '{"Content-type":"application/json"}',
    json_build_object('record', new)::text
  );
  return new;
end;
$$;


-- Trigger to call the function on new user signup
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();
