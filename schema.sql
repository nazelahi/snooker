
-- Enable HTTP extension
create extension if not exists http with schema extensions;

-- Create is_admin function
create or replace function public.is_admin()
returns boolean as $$
begin
  return (select auth.jwt()->>'email') = 'admin@gmail.com';
end;
$$ language plpgsql security definer;


-- Create Players Table
create table public.players (
  id uuid not null primary key references auth.users(id) on delete cascade,
  created_at timestamp with time zone not null default now(),
  name text not null,
  email text,
  skill_level text not null default 'Beginner',
  matches_played integer not null default 0,
  win_rate text not null default '0%',
  highest_break integer not null default 0,
  avatar text,
  initials text,
  wins integer,
  losses integer,
  average_break integer
);
alter table public.players enable row level security;
create policy "Players are viewable by everyone." on public.players for select using (true);
create policy "Users can insert their own player profile." on public.players for insert with check (auth.uid() = id);
create policy "Users can update their own player profile." on public.players for update using (auth.uid() = id);
create policy "Admins can do anything." on public.players for all using (public.is_admin());


-- Create Tournaments Table
create table public.tournaments (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone not null default now(),
  name text not null,
  format text not null,
  players integer not null,
  status text not null,
  rules text[],
  image text,
  pendingPlayers text[],
  registeredPlayers text[],
  location text,
  winner text,
  bracket jsonb
);
alter table public.tournaments enable row level security;
create policy "Tournaments are viewable by everyone." on public.tournaments for select using (true);
create policy "Admins can create tournaments." on public.tournaments for insert with check (public.is_admin());
create policy "Admins and users can update tournaments (for registration)." on public.tournaments for update using (true);
create policy "Admins can delete tournaments." on public.tournaments for delete using (public.is_admin());


-- Create Matches Table
create table public.matches (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone not null default now(),
  winner text not null,
  loser text not null,
  score text not null,
  date timestamp with time zone not null,
  media text[],
  comments jsonb,
  pending_score jsonb,
  tournament_id bigint references public.tournaments(id)
);
alter table public.matches enable row level security;
create policy "Matches are viewable by everyone." on public.matches for select using (true);
create policy "Authenticated users can create matches." on public.matches for insert with check (auth.role() = 'authenticated');
create policy "Users can update their own matches." on public.matches for update using (
  (auth.jwt() ->> 'email') = (select email from public.players where name = winner) OR
  (auth.jwt() ->> 'email') = (select email from public.players where name = loser)
);
create policy "Admins can do anything." on public.matches for all using (public.is_admin());


-- Create Upcoming Matches Table
create table public.upcoming_matches (
    id bigint generated by default as identity not null,
    created_at timestamp with time zone not null default now(),
    player1 text not null,
    player2 text not null,
    date date not null,
    time time without time zone not null,
    tournament_id bigint,
    constraint upcoming_matches_pkey primary key (id),
    constraint upcoming_matches_tournament_id_fkey foreign key (tournament_id) references tournaments (id)
);
alter table public.upcoming_matches enable row level security;
create policy "Upcoming matches are viewable by everyone." on public.upcoming_matches for select using (true);
create policy "Admins can manage upcoming matches." on public.upcoming_matches for all using (public.is_admin());


-- Live Matches View
create or replace view public.live_matches as
  SELECT um.id,
    t.id AS tournament_id,
    t.name AS tournament_name,
    um.player1,
    um.player2,
    floor(random() * 5.0) AS score1,
    floor(random() * 5.0) AS score2
  FROM (public.upcoming_matches um
    JOIN public.tournaments t ON ((um.tournament_id = t.id)))
  WHERE (t.status = 'In Progress'::text);

-- Create Notices Table
create table public.notices (
    id bigint generated by default as identity not null,
    created_at timestamp with time zone not null default now(),
    title text not null,
    content text not null,
    date date not null,
    constraint notices_pkey primary key (id)
);
alter table public.notices enable row level security;
create policy "Notices are viewable by everyone." on public.notices for select using (true);
create policy "Admins can manage notices." on public.notices for all using (public.is_admin());

-- Create Notifications Table
create table public.notifications (
    id bigint generated by default as identity not null,
    created_at timestamp with time zone not null default now(),
    user_name text not null,
    title text not null,
    description text not null,
    read boolean not null default false,
    date timestamp with time zone not null,
    link text,
    constraint notifications_pkey primary key (id)
);
alter table public.notifications enable row level security;
create policy "Users can view their own notifications." on public.notifications for select using ((auth.jwt() ->> 'email') = (select email from public.players where name = user_name));
create policy "Users can update their own notifications." on public.notifications for update using ((auth.jwt() ->> 'email') = (select email from public.players where name = user_name));
create policy "Users can delete their own notifications." on public.notifications for delete using ((auth.jwt() ->> 'email') = (select email from public.players where name = user_name));
create policy "System can insert notifications." on public.notifications for insert with check (true);


-- Create Settings Table
create table public.settings (
    key text not null,
    value jsonb,
    constraint settings_pkey primary key (key)
);
alter table public.settings enable row level security;
create policy "Settings are readable by everyone" on public.settings for select using (true);
create policy "Admins can manage settings" on public.settings for all using (public.is_admin());


