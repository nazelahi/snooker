-- Create Players Table
CREATE TABLE public.players (
  id uuid NOT NULL PRIMARY KEY REFERENCES auth.users(id),
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  name text NOT NULL,
  email text UNIQUE,
  skill_level text NOT NULL DEFAULT 'Beginner'::text,
  matches_played integer NOT NULL DEFAULT 0,
  win_rate text NOT NULL DEFAULT '0%'::text,
  highest_break integer NOT NULL DEFAULT 0,
  avatar text,
  initials text,
  wins integer DEFAULT 0,
  losses integer DEFAULT 0,
  average_break integer DEFAULT 0
);

-- Create Tournaments Table
CREATE TABLE public.tournaments (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  name text NOT NULL,
  format text,
  players integer,
  status text,
  rules text[],
  image text,
  pendingPlayers text[],
  registeredPlayers text[],
  location text,
  winner text,
  bracket jsonb
);

-- Create Matches Table
CREATE TABLE public.matches (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  winner text NOT NULL,
  loser text NOT NULL,
  score text NOT NULL,
  date timestamp with time zone NOT NULL,
  media text[],
  comments jsonb,
  pending_score jsonb,
  tournament_id bigint REFERENCES public.tournaments(id)
);

-- Create Upcoming Matches Table
CREATE TABLE public.upcoming_matches (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  player1 text NOT NULL,
  player2 text NOT NULL,
  date date NOT NULL,
  time time without time zone NOT NULL,
  tournament_id bigint REFERENCES public.tournaments(id)
);

-- Create Notices Table
CREATE TABLE public.notices (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL,
    title TEXT NOT NULL,
    content TEXT NOT NULL,
    date TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL
);


-- Create Live Matches View
CREATE OR REPLACE VIEW public.live_matches AS
 SELECT um.id,
    t.id AS tournament_id,
    t.name AS tournament_name,
    um.player1,
    um.player2,
    0 AS score1,
    0 AS score2
   FROM (public.upcoming_matches um
     LEFT JOIN public.tournaments t ON ((um.tournament_id = t.id)))
  WHERE ((um.date = CURRENT_DATE) AND (um.time <= CURRENT_TIME));


-- Create Settings Table
CREATE TABLE public.settings (
    key TEXT PRIMARY KEY,
    value JSONB
);

-- Create Notifications Table
CREATE TABLE public.notifications (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL,
    user_name TEXT NOT NULL,
    title TEXT NOT NULL,
    description TEXT NOT NULL,
    read BOOLEAN DEFAULT FALSE NOT NULL,
    date TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL,
    link TEXT
);


