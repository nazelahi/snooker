-- Create a table for public players
create table players (
  id uuid references auth.users(id) not null primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  name text,
  email text,
  skill_level text default 'Beginner'::text,
  matches_played integer default 0,
  win_rate text default '0%'::text,
  highest_break integer default 0,
  avatar text,
  initials text,
  wins integer default 0,
  losses integer default 0,
  average_break integer default 0
);

-- Create a table for matches
create table matches (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  winner text,
  loser text,
  score text,
  date date,
  media text[],
  "comments" jsonb,
  pending_score jsonb,
  tournament_id bigint
);

-- Create a table for upcoming matches
create table upcoming_matches (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  player1 text,
  player2 text,
  date date,
  time time without time zone,
  tournament_id bigint
);

-- Create a table for tournaments
create table tournaments (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  name text,
  format text,
  players integer,
  status text,
  rules text[],
  image text,
  "pendingPlayers" text[],
  "registeredPlayers" text[],
  location text,
  winner text,
  bracket jsonb
);

-- Create a table for notices
create table notices (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    title text,
    content text,
    date timestamp with time zone
);

-- Create a table for notifications
create table notifications (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    user_name text,
    title text,
    description text,
    read boolean default false,
    date timestamp with time zone,
    link text
);

-- Create a table for general settings
create table settings (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    key text unique,
    value jsonb
);

-- Create a view for live matches
create view live_matches as
  SELECT um.id,
    t.id AS tournament_id,
    t.name AS tournament_name,
    um.player1,
    um.player2,
    0 AS score1,
    0 AS score2
   FROM (upcoming_matches um
     JOIN tournaments t ON ((um.tournament_id = t.id)))
  WHERE (t.status = 'In Progress'::text);

