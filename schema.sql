insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('avatars', 'avatars', true, 5242880, '{"image/jpeg","image/png","image/gif"}') on conflict (id) do nothing;
create policy "Avatar images are publicly accessible." on storage.objects for
select using (bucket_id = 'avatars');
create policy "Anyone can upload an avatar." on storage.objects for
insert with check (bucket_id = 'avatars');
create policy "Anyone can update their own avatar." on storage.objects for
update with check (
  bucket_id = 'avatars'
  and auth.uid() = (storage.foldername(name))[1] :: uuid
);
--
-- Function to create a public player profile for a new user
--
create or replace function public.handle_new_user() returns trigger as $$
begin
  insert into public.players (id, name, email, initials, avatar)
  values (
    new.id,
    new.raw_user_meta_data ->> 'full_name',
    new.email,
    (
      select string_agg(substring(name, 1, 1), '')
      from unnest(string_to_array(new.raw_user_meta_data ->> 'full_name', ' ')) as name
    ),
    new.raw_user_meta_data ->> 'avatar_url'
  );
  return new;
end;
$$ language plpgsql security definer;
--
-- Trigger to call the function when a new user signs up
--
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after
insert on auth.users for each row execute procedure public.handle_new_user();
