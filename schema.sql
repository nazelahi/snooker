--
-- Create a table for public profiles
--
create table if not exists players (
  id uuid not null primary key,
  created_at timestamp with time zone default now() not null,
  name text not null,
  email text,
  skill_level text default 'Beginner'::text not null,
  matches_played integer default 0 not null,
  win_rate text default '0%'::text not null,
  highest_break integer default 0 not null,
  avatar text,
  initials text,
  wins integer,
  losses integer,
  average_break integer
);
alter table players enable row level security;
create policy "Public profiles are viewable by everyone." on players for
select using (true);
create policy "Users can insert their own profile." on players for
insert with check (auth.uid() = id);
create policy "Users can update own profile." on players for
update using (auth.uid() = id);
create policy "Admins can update any profile." on players for
update using (
  (
    select auth.jwt() ->> 'email'
  ) = 'admin@gmail.com'
);
create policy "Admins can delete any profile." on players for delete using (
  (
    select auth.jwt() ->> 'email'
  ) = 'admin@gmail.com'
);
