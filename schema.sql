-- Create the is_admin function
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean AS $$
BEGIN
  RETURN (auth.jwt()->>'email') = 'admin@gmail.com';
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Create the players table
CREATE TABLE public.players (
    id uuid NOT NULL,
    name text NOT NULL,
    email text,
    skill_level text DEFAULT 'Beginner'::text NOT NULL,
    matches_played integer DEFAULT 0 NOT NULL,
    win_rate text DEFAULT '0%'::text NOT NULL,
    highest_break integer DEFAULT 0 NOT NULL,
    avatar text,
    initials text,
    wins integer DEFAULT 0,
    losses integer DEFAULT 0,
    average_break integer DEFAULT 0,
    created_at timestamp with time zone DEFAULT now() NOT NULL
);

ALTER TABLE public.players ADD CONSTRAINT players_pkey PRIMARY KEY (id);
ALTER TABLE public.players ADD CONSTRAINT players_id_fkey FOREIGN KEY (id) REFERENCES auth.users(id) ON DELETE CASCADE;

-- Create tournaments table
CREATE TABLE public.tournaments (
    id bigint generated by default as identity,
    name text not null,
    format text not null,
    players integer not null,
    status text not null,
    rules text[],
    image text,
    pendingPlayers text[],
    registeredPlayers text[],
    location text,
    winner text,
    bracket jsonb,
    primary key (id)
);

-- Create matches table
CREATE TABLE public.matches (
    id bigint generated by default as identity,
    winner text not null,
    loser text not null,
    score text not null,
    date timestamp with time zone not null,
    media text[],
    comments jsonb,
    pending_score jsonb,
    tournament_id bigint,
    primary key (id),
    foreign key (tournament_id) references tournaments (id)
);

-- Create upcoming_matches table
CREATE TABLE public.upcoming_matches (
    id bigint generated by default as identity,
    player1 text not null,
    player2 text not null,
    date date not null,
    time time without time zone not null,
    tournament_id bigint,
    primary key (id),
    foreign key (tournament_id) references tournaments (id)
);

-- Create settings table
CREATE TABLE public.settings (
    id bigint generated by default as identity,
    key text not null,
    value jsonb,
    primary key (id),
    unique (key)
);

-- Create notices table
CREATE TABLE public.notices (
    id bigint generated by default as identity,
    title text not null,
    content text not null,
    date timestamp with time zone not null,
    created_at timestamp with time zone default now(),
    primary key (id)
);

-- Create notifications table
CREATE TABLE public.notifications (
    id bigint generated by default as identity,
    user_name text not null,
    title text not null,
    description text not null,
    read boolean default false,
    date timestamp with time zone not null,
    link text,
    created_at timestamp with time zone default now(),
    primary key (id)
);

-- Create the live_matches view
CREATE OR REPLACE VIEW public.live_matches AS
 SELECT um.id,
    um.tournament_id,
    t.name AS tournament_name,
    um.player1,
    um.player2,
    floor(random() * 5::double precision) AS score1,
    floor(random() * 5::double precision) AS score2
   FROM (public.upcoming_matches um
     JOIN public.tournaments t ON ((um.tournament_id = t.id)))
  WHERE ((t.status = 'In Progress'::text) AND (um.date <= now()));


